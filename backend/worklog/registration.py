"""Agent self-registration: an enrolled agent registers a separate identity for itself.

The registering agent's own credential is the authority, so every identity still
descends from a credential the person issued in Settings. The agent generates the
new token and Worklog stores only its SHA-256, like a credential issued in Settings.
The registered credential's row in communication_credentials says who registered it and the
chat the new identity works in (since v12; before, only the `credential.register` event did):
its runs report that chat, and work they report tracks it. Since v18 the row and the event also
hold the directory the agent registered from, which Review shows beside its proposals. A
registered identity gets the same agent scope as any other, nothing more, and it
loses access with the identity that registered it.

A chat often ends before its work does. The identity it registered then continues in the next
chat (continue_identity): a new credential of the same identity, registered with the new chat,
replaces the old one as rotating a token in Settings does. Everything the identity holds stays
with it, since each of those records names the identity: its roles, ties, tickets, proposals and
the requests waiting on it. Only what names the old chat moves, and the old chat's runs end.
"""

from __future__ import annotations

import hashlib
import sqlite3
from collections.abc import Callable, Iterable
from pathlib import PurePosixPath, PureWindowsPath

from fastapi import FastAPI, Request
from pydantic import Field

from . import record_kinds
