"""Agent self-registration: an enrolled agent registers a separate identity for itself.

The registering agent's own credential is the authority, so every identity still
descends from a credential the person issued in Settings. The agent generates the
new token and Worklog stores only its SHA-256, like a credential issued in Settings.
The `credential.register` event is the one record of who registered whom, and of the
chat the new identity works in: its runs report that chat, and work they report tracks it. A
registered identity gets the same agent scope as any other, nothing more, and it
loses access with the identity that registered it.
"""

from __future__ import annotations

import hashlib
import json
import sqlite3
from collections.abc import Callable, Iterable

from fastapi import FastAPI, Request
from pydantic import Field

from .common import AppError, event, now, setting, text, today, uid
from .coordination import close_credential_runs
from .db import Database
from .discussions import bind_credential, communication_actor
from .models import Command

# Stop a registration loop. Credentials issued in Settings neither count nor are refused.
ACTIVE_LIMIT = 200
DAILY_LIMIT = 200
# A random token of the minimum length shows dozens; this only refuses a constant or a pattern.
DISTINCT_TOKEN_CHARACTERS = 10
_ROUTES = {"/agent-registrations", "/agent-registrations/retire"}


class AgentRegistration(Command):
    label: str
    # Generated by the registering agent, such as Python's secrets.token_urlsafe(32).
    token: str = Field(min_length=43, max_length=200, pattern=r"^[A-Za-z0-9_-]+$")
    # The chat the identity works in: a Claude Code session ID, a Claude desktop local_ ID or a
    # Codex thread ID. Its runs report it unless they name another, and the work they report
    # tracks it.
    chatId: str = Field(min_length=1, max_length=500)
    # A name from GET /discussions/avatars; omitted draws the least-used one.
    avatar: str | None = Field(default=None, min_length=1, max_length=100)


def agent_route_allowed(method: str, path: str) -> bool:
    return method == "POST" and path.removeprefix("/api/v1") in _ROUTES


def registered_by(c: sqlite3.Connection, credential_ids: Iterable[str]) -> dict[str, dict]:
    """The registering agent of each credential; ones issued in Settings are absent."""
    ids = list(dict.fromkeys(credential_ids))
    found: dict[str, dict] = {}
    for start in range(0, len(ids), 500):
        chunk = ids[start:start + 500]
        rows = c.execute("SELECT entity_id,after_json FROM events WHERE kind='credential.register' AND entity_id IN ({})".format(",".join("?" * len(chunk))), chunk)
        found.update((row[0], json.loads(row[1])["registeredBy"]) for row in rows)
    return found


def registered_chats(c: sqlite3.Connection, credential_ids: Iterable[str]) -> dict[str, str]:
    """The chat each registered credential's identity works in; ones issued in Settings, or
    registered before registration named a chat, are absent."""
    ids = list(dict.fromkeys(credential_ids))
    found: dict[str, str] = {}
    for start in range(0, len(ids), 500):
        chunk = ids[start:start + 500]
        rows = c.execute("SELECT entity_id,after_json FROM events WHERE kind='credential.register' AND entity_id IN ({})".format(",".join("?" * len(chunk))), chunk)
        for identity, after in rows:
            chat = json.loads(after).get("chatId")
            if chat:
                found[identity] = chat
    return found


def identity_chat(c: sqlite3.Connection, agent_id: str) -> str | None:
    """The chat an identity registered with, whichever of its credentials registered it:
    rotating the credential in Settings keeps the identity, and so its chat."""
    credentials = [r[0] for r in c.execute("SELECT credential_id FROM communication_credentials WHERE agent_id=?", (agent_id,))]
    return next(iter(registered_chats(c, credentials).values()), None)


def _registered(c: sqlite3.Connection) -> Callable[[str], list[str]]:
    """Every identity an identity registered, directly or through the ones it registered."""
    children: dict[str, list[str]] = {}
    for (after,) in c.execute("SELECT after_json FROM events WHERE kind='credential.register'"):
        record = json.loads(after)
        children.setdefault(record["registeredBy"]["id"], []).append(record["agentId"])

    def descendants(agent_id: str) -> list[str]:
        found: list[str] = []
        seen = {agent_id}
        pending = list(children.get(agent_id, []))
        while pending:
            child = pending.pop()
            if child not in seen:
                seen.add(child)
                found.append(child)
                pending.extend(children.get(child, []))
        return found

    return descendants


def active_registrations(c: sqlite3.Connection, agent_ids: Iterable[str]) -> dict[str, int]:
    """How many active identities each identity registered, which revoking it revokes too."""
    descendants = _registered(c)
    active = {row[0] for row in c.execute("SELECT DISTINCT cc.agent_id FROM communication_credentials cc JOIN credentials cr ON cr.id=cc.credential_id WHERE cr.revoked=0")}
    return {agent_id: sum(child in active for child in descendants(agent_id)) for agent_id in set(agent_ids)}


def revoke_registered(c: sqlite3.Connection, actor: dict, credential_id: str) -> int:
    """Revoke every identity the credential's identity registered; returns how many credentials."""
    binding = c.execute("SELECT agent_id FROM communication_credentials WHERE credential_id=?", (credential_id,)).fetchone()
    if binding is None:
        return 0
    revoked = 0
    for agent_id in _registered(c)(binding[0]):
        for (child,) in c.execute("SELECT cr.id FROM credentials cr JOIN communication_credentials cc ON cc.credential_id=cr.id WHERE cc.agent_id=? AND cr.revoked=0", (agent_id,)).fetchall():
            c.execute("UPDATE credentials SET revoked=1 WHERE id=?", (child,))
            close_credential_runs(c, actor, child)
            event(c, actor, "credential.revoke", child, None, {"revoked": True, "via": credential_id})
            revoked += 1
    return revoked


def _record(c: sqlite3.Connection, credential_id: str) -> dict:
    row = c.execute("SELECT cr.id,cr.label,a.id AS agent_id,a.avatar FROM credentials cr JOIN communication_credentials cc ON cc.credential_id=cr.id JOIN communication_agents a ON a.id=cc.agent_id WHERE cr.id=?", (credential_id,)).fetchone()
    return {"id": row["id"], "agentId": row["agent_id"], "label": row["label"], "avatar": row["avatar"],
            "chatId": registered_chats(c, [credential_id]).get(credential_id),
            "registeredBy": registered_by(c, [credential_id]).get(credential_id)}


def register(c: sqlite3.Connection, actor: dict, p: dict) -> dict:
    if actor["kind"] != "agent":
        raise AppError(403, "agent_scope", "Agents register themselves; issue a credential for an agent in Settings")
    # Middleware authentication precedes the write lock; revoke may win that race.
    sponsor = communication_actor(c, actor)
    if len(set(p["token"])) < DISTINCT_TOKEN_CHARACTERS:
        raise AppError(422, "validation", "Generate the token from at least 32 random bytes", {"token": "invalid"})
    chat = text(p.get("chatId"), "chatId", required=True, limit=500)
    if any(ch.isspace() or ord(ch) < 32 for ch in chat):
        raise AppError(422, "validation", "Give the chat's ID as it is, without spaces", {"chatId": "invalid"})
    digest = hashlib.sha256(p["token"].encode()).hexdigest()
    existing = c.execute("SELECT id,revoked FROM credentials WHERE token_hash=?", (digest,)).fetchone()
    if existing is not None:
        if existing["revoked"]:
            raise AppError(409, "token_revoked", "This token was revoked; generate a new one to register again")
        # The token is the idempotency key: retrying an uncertain registration returns it.
        if existing["id"] not in registered_by(c, [existing["id"]]):
            raise AppError(409, "token_in_use", "This token belongs to a credential issued in Settings; generate a new one")
        # An identity works in the one chat it registered with; another chat registers another identity.
        recorded = registered_chats(c, [existing["id"]]).get(existing["id"])
        if recorded != chat:
            where = "another chat" if recorded else "no chat, as registered before chats were recorded"
            raise AppError(409, "chat_mismatch", f"This name's identity works in {where}; register a new name for this chat", {"chatId": "mismatch"})
        return _record(c, existing["id"])
    label = text(p["label"], "label", required=True, limit=200)
    if label.casefold() == "you":
        raise AppError(422, "validation", "Choose another label; You names the person in discussions", {"label": "invalid"})
    active = c.execute("SELECT count(*) FROM credentials cr WHERE cr.revoked=0 AND EXISTS(SELECT 1 FROM events e WHERE e.entity_id=cr.id AND e.kind='credential.register')").fetchone()[0]
    if active >= ACTIVE_LIMIT:
        raise AppError(429, "agent_limit", f"{ACTIVE_LIMIT} registered agents are already active; retire or revoke unused ones first")
    registered_today = c.execute("SELECT count(*) FROM events WHERE local_date=? AND kind='credential.register'",
                                 (today(setting(c, "timezone", "America/Chicago")),)).fetchone()[0]
    if registered_today >= DAILY_LIMIT:
        raise AppError(429, "agent_limit", f"Agents registered {DAILY_LIMIT} identities today; registering resumes tomorrow")
    identity = uid()
    c.execute("INSERT INTO credentials VALUES(?,?,?,?,0)", (identity, label, digest, now()))
    agent = bind_credential(c, identity, label, avatar=p["avatar"])
    event(c, actor, "credential.register", identity, None, {"label": label, "avatar": agent["avatar"], "agentId": agent["id"],
                                                             "registeredBy": {"id": sponsor["id"], "label": sponsor["label"]},
                                                             "chatId": chat})
    return _record(c, identity)


def retire(c: sqlite3.Connection, actor: dict) -> dict:
    if actor["kind"] != "agent":
        raise AppError(403, "agent_scope", "Revoke credentials in Settings")
    agent = communication_actor(c, actor)
    # A credential issued in Settings may be shared by other agents; only the person revokes it.
    if actor["id"] not in registered_by(c, [actor["id"]]):
        raise AppError(403, "agent_scope", "Only a credential an agent registered can retire itself; revoke this one in Settings")
    c.execute("UPDATE credentials SET revoked=1 WHERE id=?", (actor["id"],))
    close_credential_runs(c, actor, actor["id"], "credential_retired")
    event(c, actor, "credential.retire", actor["id"], None, {"revoked": True})
    return {"id": actor["id"], "agentId": agent["id"], "retired": True, "registeredRevoked": revoke_registered(c, actor, actor["id"])}


def install_registration_routes(app: FastAPI, db: Database, before_write: Callable[[], None]) -> None:
    def write(request: Request, fn: Callable[[sqlite3.Connection, dict], dict]) -> dict:
        # Not a receipt-backed mutation: a receipt's request hash would be derived from the token.
        before_write()
        with db.transaction() as c:
            return fn(c, request.state.actor)

    @app.post("/api/v1/agent-registrations")
    def register_agent(request: Request, body: AgentRegistration) -> dict:
        return write(request, lambda c, actor: register(c, actor, body.model_dump()))

    @app.post("/api/v1/agent-registrations/retire")
    def retire_agent(request: Request) -> dict:
        return write(request, retire)
