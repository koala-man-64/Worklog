# Stop a registration loop. Credentials issued in Settings neither count nor are refused. A
# continuation counts toward the daily limit too: each one adds a credential.
ACTIVE_LIMIT = 200
DAILY_LIMIT = 200
# A random token of the minimum length shows dozens; this only refuses a constant or a pattern.
DISTINCT_TOKEN_CHARACTERS = 10


class AgentRegistration(Command):
    label: str
    # Generated by the registering agent, such as Python's secrets.token_urlsafe(32).
    token: str = Field(min_length=43, max_length=200, pattern=r"^[A-Za-z0-9_-]+$")
    # The chat the identity works in: a Claude Code session ID, a Claude desktop local_ ID or a
    # Codex thread ID. Its runs report it unless they name another, and the work they report
    # tracks it.
    chatId: str = Field(min_length=1, max_length=500)
    # A name from GET /discussions/avatars; omitted draws the least-used one.
    avatar: str | None = Field(default=None, min_length=1, max_length=100)
    # The absolute directory the agent works in; `worklog agent register` sends its current one.
    # Review shows it beside the identity's proposals. Omitted, it stays unknown.
    directory: str | None = Field(default=None, min_length=1, max_length=2000)


class AgentContinuation(Command):
    """The calling identity continues in another chat; its label and avatar stay its own."""

    # The new credential's token, generated by the continuing agent as for a registration.
    token: str = Field(min_length=43, max_length=200, pattern=r"^[A-Za-z0-9_-]+$")
    # The chat the identity works in from now on.
    chatId: str = Field(min_length=1, max_length=500)
    # The directory the new chat works in, which Review shows beside the proposals made there.
    directory: str | None = Field(default=None, min_length=1, max_length=2000)


# Moves what names an identity's old chat to its new one, and returns the new chat's tracked
# records: support.continue_chats, which app.py passes in because supporting records sit above this
# module (test_layering.py).
ChatMover = Callable[[sqlite3.Connection, dict, str, str], list[dict]]


def _registered(c: sqlite3.Connection) -> Callable[[str], list[str]]:
    """Every identity an identity registered, directly or through the ones it registered."""
    children: dict[str, list[str]] = {}
    for sponsor, child in c.execute("SELECT registered_by,agent_id FROM communication_credentials WHERE registered_by IS NOT NULL"):
        children.setdefault(sponsor, []).append(child)

    def descendants(agent_id: str) -> list[str]:
        found: list[str] = []
        seen = {agent_id}
        pending = list(children.get(agent_id, []))
        while pending:
            child = pending.pop()
            if child not in seen:
                seen.add(child)
                found.append(child)
                pending.extend(children.get(child, []))
        return found

    return descendants


def active_registrations(c: sqlite3.Connection, agent_ids: Iterable[str]) -> dict[str, int]:
    """How many active identities each identity registered, which revoking it revokes too."""
    descendants = _registered(c)
    active = {row[0] for row in c.execute("SELECT DISTINCT cc.agent_id FROM communication_credentials cc JOIN credentials cr ON cr.id=cc.credential_id WHERE cr.revoked=0")}
    return {agent_id: sum(child in active for child in descendants(agent_id)) for agent_id in set(agent_ids)}


def revoke_registered(c: sqlite3.Connection, actor: dict, credential_id: str) -> int:
    """Revoke every identity the credential's identity registered; returns how many credentials."""
    binding = c.execute("SELECT agent_id FROM communication_credentials WHERE credential_id=?", (credential_id,)).fetchone()
    if binding is None:
        return 0
    revoked = 0
    for agent_id in _registered(c)(binding[0]):
        for (child,) in c.execute("SELECT cr.id FROM credentials cr JOIN communication_credentials cc ON cc.credential_id=cr.id WHERE cc.agent_id=? AND cr.revoked=0", (agent_id,)).fetchall():
            c.execute("UPDATE credentials SET revoked=1 WHERE id=?", (child,))
            close_credential_runs(c, actor, child)
            event(c, actor, "credential.revoke", child, None, {"revoked": True, "via": credential_id})
            revoked += 1
    return revoked


def _directory(value: object) -> str | None:
    """The directory an agent registers from: absolute, on Windows or POSIX, and every character
    shown as itself, so no control or bidirectional formatting character can make Review show
    another path."""
    if value is None:
        return None
    directory = text(value, "directory", required=True, limit=2000)
    if not shows_as_written(directory) or not (PureWindowsPath(directory).is_absolute() or PurePosixPath(directory).is_absolute()):
        raise AppError(422, "validation", "Give the absolute directory you work in, as your shell reports it", {"directory": "invalid"})
    return directory


def _record(c: sqlite3.Connection, credential_id: str) -> dict:
    row = c.execute("SELECT cr.id,cr.label,a.id AS agent_id,a.avatar,cc.directory FROM credentials cr JOIN communication_credentials cc ON cc.credential_id=cr.id JOIN communication_agents a ON a.id=cc.agent_id WHERE cr.id=?", (credential_id,)).fetchone()
    return {"id": row["id"], "agentId": row["agent_id"], "label": row["label"], "avatar": row["avatar"],
            "chatId": registered_chats(c, [credential_id]).get(credential_id),
            "registeredBy": registered_by(c, [credential_id]).get(credential_id),
            "directory": row["directory"]}


def _token_digest(token: str) -> str:
    if len(set(token)) < DISTINCT_TOKEN_CHARACTERS:
        raise AppError(422, "validation", "Generate the token from at least 32 random bytes", {"token": "invalid"})
    return hashlib.sha256(token.encode()).hexdigest()


def _chat(value: object) -> str:
    chat = text(value, "chatId", required=True, limit=500)
    if any(ch.isspace() or ord(ch) < 32 for ch in chat):
        raise AppError(422, "validation", "Give the chat's ID as it is, without spaces", {"chatId": "invalid"})
    return chat


def _added_today(c: sqlite3.Connection) -> int:
    """Credentials agents added today, by registering or continuing identities."""
    return c.execute("SELECT count(*) FROM events WHERE local_date=? AND kind IN ('credential.register','credential.continue')",
                     (today(setting(c, "timezone", "America/Chicago")),)).fetchone()[0]


def register(c: sqlite3.Connection, actor: dict, p: dict) -> dict:
    if actor["kind"] != "agent":
        raise AppError(403, "agent_scope", "Agents register themselves; issue a credential for an agent in Settings")
    # Middleware authentication precedes the write lock; revoke may win that race.
    sponsor = communication_actor(c, actor)
    digest = _token_digest(p["token"])
    chat = _chat(p.get("chatId"))
    directory = _directory(p.get("directory"))
    existing = c.execute("SELECT id,revoked FROM credentials WHERE token_hash=?", (digest,)).fetchone()
    if existing is not None:
        if existing["revoked"]:
            raise AppError(409, "token_revoked", "This token was revoked; generate a new one to register again")
        # The token is the idempotency key: retrying an uncertain registration returns it, with the
        # directory it first recorded.
        if existing["id"] not in registered_by(c, [existing["id"]]):
            raise AppError(409, "token_in_use", "This token belongs to a credential issued in Settings; generate a new one")
        # An identity works in the one chat it registered with; another chat registers another identity.
        recorded = registered_chats(c, [existing["id"]]).get(existing["id"])
        if recorded != chat:
            where = "another chat" if recorded else "no chat, as registered before chats were recorded"
            raise AppError(409, "chat_mismatch", f"This name's identity works in {where}; register a new name for this chat", {"chatId": "mismatch"})
        return _record(c, existing["id"])
    label = text(p["label"], "label", required=True, limit=200)
    if label.casefold() == "you":
        raise AppError(422, "validation", "Choose another label; You names the person in discussions", {"label": "invalid"})
    active = c.execute("SELECT count(*) FROM credentials cr JOIN communication_credentials cc ON cc.credential_id=cr.id "
                       "WHERE cr.revoked=0 AND cc.registered_by IS NOT NULL").fetchone()[0]
    if active >= ACTIVE_LIMIT:
        raise AppError(429, "agent_limit", f"{ACTIVE_LIMIT} registered agents are already active; retire or revoke unused ones first")
    if _added_today(c) >= DAILY_LIMIT:
        raise AppError(429, "agent_limit", f"Agents registered {DAILY_LIMIT} identities today; registering resumes tomorrow")
    identity = uid()
    c.execute("INSERT INTO credentials(id,label,token_hash,created_at,revoked) VALUES(?,?,?,?,0)", (identity, label, digest, now()))
    agent = bind_credential(c, identity, label, avatar=p["avatar"])
    c.execute("UPDATE communication_credentials SET registered_by=?,registered_by_label=?,chat_id=?,directory=? WHERE credential_id=?",
              (sponsor["id"], sponsor["label"], chat, directory, identity))
    event(c, actor, "credential.register", identity, None, {"label": label, "avatar": agent["avatar"], "agentId": agent["id"],
                                                             "registeredBy": {"id": sponsor["id"], "label": sponsor["label"]},
                                                             "chatId": chat, "directory": directory})
    return _record(c, identity)


def retire(c: sqlite3.Connection, actor: dict) -> dict:
    if actor["kind"] != "agent":
        raise AppError(403, "agent_scope", "Revoke credentials in Settings")
    agent = communication_actor(c, actor)
    # A credential issued in Settings may be shared by other agents; only the person revokes it.
    if actor["id"] not in registered_by(c, [actor["id"]]):
        raise AppError(403, "agent_scope", "Only a credential an agent registered can retire itself; revoke this one in Settings")
    c.execute("UPDATE credentials SET revoked=1 WHERE id=?", (actor["id"],))
    close_credential_runs(c, actor, actor["id"], "credential_retired")
    event(c, actor, "credential.retire", actor["id"], None, {"revoked": True})
    return {"id": actor["id"], "agentId": agent["id"], "retired": True, "registeredRevoked": revoke_registered(c, actor, actor["id"])}


def _roles(c: sqlite3.Connection, agent_id: str) -> list[dict]:
    """The responsibility roles an identity owns, each with the title of the record it is on."""
    rows = c.execute("SELECT id,label,context_type,context_id FROM discussion_roles WHERE owner_id=? ORDER BY updated_at DESC,id",
                     (agent_id,)).fetchall()
    titles = {r["id"]: r["title"] for kind in ("item", "roadmap", "step")
              for r in record_kinds.rows(c, kind, [row["context_id"] for row in rows if row["context_type"] == kind])}
    return [{"id": r["id"], "label": r["label"], "contextType": r["context_type"], "contextId": r["context_id"],
             "contextTitle": titles.get(r["context_id"])} for r in rows]


def continue_identity(c: sqlite3.Connection, actor: dict, p: dict, move_chats: ChatMover) -> dict:
    """The calling identity continues in a new chat, because the chat it worked in ended first.

    A new credential of the same identity, registered with the new chat by the identity's own
    sponsor, replaces every live one the identity has, as rotation does: their runs end, so their
    participation is released, and their tokens stop working. The identity keeps its label, avatar
    and everything that names it. Wherever its old chat is tracked, the new chat takes over
    (support.continue_chats). The identity's registration names the old chat; the new credential
    names the new one, and its runs report that one from now on (discussions.identity_chat).
    """
    if actor["kind"] != "agent":
        raise AppError(403, "agent_scope", "Agents continue their own identities; issue a credential for an agent in Settings")
    agent = communication_actor(c, actor)
    # The identity's registration, whichever of its credentials holds it: rotating a token in
    # Settings binds a credential that names no sponsor.
    sponsor = c.execute("SELECT registered_by,registered_by_label FROM communication_credentials "
                        "WHERE agent_id=? AND registered_by IS NOT NULL LIMIT 1", (agent["id"],)).fetchone()
    if sponsor is None:
        raise AppError(403, "agent_scope", "Only an identity an agent registered continues in another chat; register a new identity for this chat")
    digest = _token_digest(p["token"])
    chat = _chat(p.get("chatId"))
    directory = _directory(p.get("directory"))
    previous = identity_chat(c, agent["id"])
    if previous == chat:
        raise AppError(409, "same_chat", "Your identity works in this chat already; carry on as you are")
    if c.execute("SELECT 1 FROM credentials WHERE token_hash=?", (digest,)).fetchone():
        raise AppError(409, "token_in_use", "This token belongs to another credential; generate a new one")
    if _added_today(c) >= DAILY_LIMIT:
        raise AppError(429, "agent_limit", f"Agents registered or continued {DAILY_LIMIT} identities today; continuing resumes tomorrow")
    label = actor["label"]
    identity = uid()
    c.execute("INSERT INTO credentials(id,label,token_hash,created_at,revoked) VALUES(?,?,?,?,0)", (identity, label, digest, now()))
    bind_credential(c, identity, label, agent_id=agent["id"])
    c.execute("UPDATE communication_credentials SET registered_by=?,registered_by_label=?,chat_id=?,directory=? WHERE credential_id=?",
              (sponsor["registered_by"], sponsor["registered_by_label"], chat, directory, identity))
    chats = move_chats(c, actor, previous, chat) if previous else []
    ended = 0
    for (old,) in c.execute("SELECT cr.id FROM credentials cr JOIN communication_credentials cc ON cc.credential_id=cr.id "
                            "WHERE cc.agent_id=? AND cr.revoked=0 AND cr.id<>?", (agent["id"], identity)).fetchall():
        ended += c.execute("SELECT count(*) FROM agent_runs WHERE credential_id=? AND ended_at IS NULL", (old,)).fetchone()[0]
        close_credential_runs(c, actor, old, "credential_continued")
        # Unlike retiring, this keeps the identities it registered: the identity goes on.
        c.execute("UPDATE credentials SET revoked=1 WHERE id=?", (old,))
    event(c, actor, "credential.continue", identity, {"credentialId": actor["id"], "chatId": previous},
          {"agentId": agent["id"], "label": label, "chatId": chat, "directory": directory,
           "registeredBy": {"id": sponsor["registered_by"], "label": sponsor["registered_by_label"]}})
    return {**_record(c, identity), "continued": {"credentialId": actor["id"], "chatId": previous, "runsEnded": ended,
                                                  "chats": chats, "roles": _roles(c, agent["id"])}}


def own_registration(c: sqlite3.Connection, actor: dict) -> dict:
    """The calling credential as registering it returned it: the identity, its chat and directory."""
    if actor["kind"] != "agent":
        raise AppError(403, "agent_scope", "Agents read their own registration; credentials are in Settings")
    communication_actor(c, actor)
    return _record(c, actor["id"])


def install_registration_routes(app: FastAPI, db: Database, move_chats: ChatMover) -> None:
    def write(request: Request, fn: Callable[[sqlite3.Connection, dict], dict]) -> dict:
        # Not a receipt-backed mutation: a receipt's request hash would be derived from the token.
        with db.transaction() as c:
            return fn(c, request.state.actor)

    @app.post("/api/v1/agent-registrations", response_model=out.Registration)
    def register_agent(request: Request, body: AgentRegistration) -> dict:
        return write(request, lambda c, actor: register(c, actor, body.model_dump()))

    @app.get("/api/v1/agent-registrations/self", response_model=out.Registration)
    def registration_self(request: Request) -> dict:
        with db.read() as c:
            return own_registration(c, request.state.actor)

    @app.post("/api/v1/agent-registrations/continue", response_model=out.Continuation)
    def continue_agent(request: Request, body: AgentContinuation) -> dict:
        return write(request, lambda c, actor: continue_identity(c, actor, body.model_dump(), move_chats))

    @app.post("/api/v1/agent-registrations/retire", response_model=out.Retirement)
    def retire_agent(request: Request) -> dict:
        return write(request, retire)
